#!/usr/bin/env bash

# Sets up a second conda environment holding a newer Verilator than the one
# pinned in conda-reqs (5.022), for flows that need force/release on memory
# elements (e.g. the tidalsim state-injection testbench) — fixed in
# Verilator >= 5.042.
#
# A newer Verilator cannot be installed into .conda-env itself: every
# verilator conda package >= 5.042 requires libzlib >= 1.3.1, while every
# available riscv-tools package (ucb-bar channel, <= 1.0.8) pins zlib < 1.3.
# So the newer Verilator lives in its own env (.conda-env-verilator) and is
# exposed through wrapper scripts in .conda-env-verilator/prio-bin that only
# shadow the verilator executables — NOT the env's gcc/binutils. The
# verilated C++ must still be compiled by the main .conda-env toolchain;
# letting the verilator env's newer gcc shadow it causes GLIBCXX runtime
# mismatches.
#
# Usage:
#   ./scripts/setup-verilator-new.sh [VERSION[=BUILD]]   # default 5.050=h10c590a_0
# then, per shell that wants the newer verilator:
#   source ./env.sh
#   source ./env-verilator.sh

# exit script if any command fails
set -e
set -o pipefail

RDIR=$(git rev-parse --show-toplevel)

# get helpful utilities
source $RDIR/scripts/utils.sh

common_setup

usage() {
    echo "usage: ${0} [VERSION[=BUILD]]"
    echo ""
    echo "Creates $RDIR/.conda-env-verilator with the requested verilator"
    echo "(default: 5.050=h10c590a_0) and generates $RDIR/env-verilator.sh."
    echo ""
    echo "Options"
    echo "   --help -h : Display this message"
    exit "$1"
}

VERILATOR_SPEC="5.050=h10c590a_0"
case "${1:-}" in
    -h | --help ) usage 0 ;;
    "" ) ;;
    * ) VERILATOR_SPEC="$1" ;;
esac
VERILATOR_VERSION="${VERILATOR_SPEC%%=*}"

ENVDIR="$RDIR/.conda-env-verilator"

# Use the real conda installation, not an env-local stub: in a child script
# the `conda` shell function is not inherited, and .conda-env/bin/conda lacks
# the libmamba solver plugin a user's .condarc may request.
CONDA="${CONDA_EXE:-conda}"
if ! type "$CONDA" >& /dev/null; then
    die "ERROR: conda must be in your environment (run this after build-setup.sh)"
fi

# idempotency: skip if the requested version is already installed
if [ -x "$ENVDIR/bin/verilator" ] && "$ENVDIR/bin/verilator" --version 2>/dev/null | grep -q "Verilator $VERILATOR_VERSION "; then
    echo "$ENVDIR already has Verilator $VERILATOR_VERSION, skipping env creation"
else
    rm -rf "$ENVDIR"
    # binutils_impl_linux-64 is required: verilator's generated makefiles
    # invoke x86_64-conda-linux-gnu-ar, which the bare verilator package
    # does not provide.
    "$CONDA" create -y -p "$ENVDIR" -c conda-forge --override-channels \
        "verilator=$VERILATOR_SPEC" binutils_impl_linux-64
fi

# wrapper scripts exposing ONLY the verilator executables (see header)
mkdir -p "$ENVDIR/prio-bin"
for tool in verilator verilator_bin verilator_bin_dbg verilator_coverage; do
    cat > "$ENVDIR/prio-bin/$tool" <<EOF
#!/bin/sh
exec $ENVDIR/bin/$tool "\$@"
EOF
    chmod +x "$ENVDIR/prio-bin/$tool"
done

# opt-in activation file
cat > "$RDIR/env-verilator.sh" <<EOF
# auto-generated by scripts/setup-verilator-new.sh
# source AFTER env.sh to use verilator $VERILATOR_VERSION instead of the pinned one
PATH=$ENVDIR/prio-bin:\$PATH
EOF

# smoke check
INSTALLED_VERSION=$("$ENVDIR/prio-bin/verilator" --version)
echo "$INSTALLED_VERSION" | grep -q "Verilator $VERILATOR_VERSION " || \
    die "ERROR: installed '$INSTALLED_VERSION' does not match requested $VERILATOR_VERSION"

echo ""
echo "Installed: $INSTALLED_VERSION"
echo "To use it (per shell):"
echo "    source $RDIR/env.sh"
echo "    source $RDIR/env-verilator.sh"
